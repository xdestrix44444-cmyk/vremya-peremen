n = 0
for f in sorted(glob.glob(os.path.join(ROOT, 'data', 'events', '*.yaml'))):
    src = open(f, encoding='utf-8').read()
    doc = yaml.safe_load(src)
    if 'voucher_choices' in doc:         # файл с якорями правим текстом
        for e in doc['events']:
            if e['id'] in T and isinstance(T[e['id']], str):
                src = src.replace(f'text: "{e["text"]}"', f'text: "{T[e["id"]]}"', 1)
                n += 1
        open(f, 'w', encoding='utf-8').write(src)
        continue
    ch = False
    for e in doc['events']:
        if e['id'] in T:
            v = T[e['id']]
            if isinstance(v, list):
                e['variants'] = v; e['text'] = v[0]
            else:
                e['text'] = v
            ch = True; n += 1
    if ch:
        head = {'title': doc['title'], 'note': doc.get('note', '')}
        out = yaml.safe_dump(head, allow_unicode=True, sort_keys=False, width=200) + 'events:\n'
        for x in doc['events']:
            out += yaml.safe_dump([x], allow_unicode=True, sort_keys=False, width=200, default_flow_style=None)
        open(f, 'w', encoding='utf-8').write(out)
